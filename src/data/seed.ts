/**
 * Seed ledger — a believable three-month history so every chart, budget and
 * insight in the app has real data on first launch.
 *
 * The data is written for a Kenyan undergraduate at Moi University, Eldoret:
 * money moves through M-Pesa, a bank account and a Sacco, income arrives as
 * HELB disbursements, family upkeep and the odd freelance gig, and spending
 * looks like campus life — Khetias and Naivas runs, matatu fare to Kesses,
 * KPLC tokens, airtime, printing at the ICT centre and chai between lectures.
 *
 * All amounts are integers in minor units (cents), so `ksh(1_250)` is KSh 1,250.
 */

const ksh = (shillings: number) => Math.round(shillings * 100);

const now = new Date();
const iso = (d: Date) => d.toISOString();
const daysAgo = (n: number, hour = 12) => {
  const d = new Date(now);
  d.setDate(d.getDate() - n);
  d.setHours(hour, (n * 7) % 60, 0, 0);
  return iso(d);
};

